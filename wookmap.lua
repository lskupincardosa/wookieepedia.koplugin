--[[--
A schematic galaxy map: Wookieepedia's lettered/numbered grid, each square
shaded by the region most of its known planets belong to, and the looked-up
planet's square highlighted.

Nothing here is copied from an official map: the shading comes only from the
grid squares and regions listed in Wookieepedia's planet infoboxes
(data/galaxy_grid.lua, generated by tools/build_galaxy_grid.py).

LEARN: KOReader draws everything into a Blitbuffer (an in-memory image of the
screen). A widget's paintTo(bb, x, y) paints itself at x/y; UIManager decides
when, and how the e-ink screen gets refreshed.
]]

local Blitbuffer = require("ffi/blitbuffer")
local Device = require("device")
local Font = require("ui/font")
local FrameContainer = require("ui/widget/container/framecontainer")
local Geom = require("ui/geometry")
local GestureRange = require("ui/gesturerange")
local InputContainer = require("ui/widget/container/inputcontainer")
local TextBoxWidget = require("ui/widget/textboxwidget")
local TextWidget = require("ui/widget/textwidget")
local TitleBar = require("ui/widget/titlebar")
local UIManager = require("ui/uimanager")
local VerticalGroup = require("ui/widget/verticalgroup")
local Widget = require("ui/widget/widget")
local logger = require("logger")
local _ = require("gettext")
local T = require("ffi/util").template
local Screen = Device.screen

-- Gray level per region, from the galactic center outwards (darker = more central).
local REGION_SHADES = {
    ["Deep Core"] = Blitbuffer.COLOR_GRAY_4,
    ["Core Worlds"] = Blitbuffer.COLOR_GRAY_6,
    ["Colonies"] = Blitbuffer.COLOR_DARK_GRAY,
    ["Inner Rim"] = Blitbuffer.COLOR_GRAY_9,
    ["Expansion Region"] = Blitbuffer.COLOR_GRAY_B,
    ["Mid Rim"] = Blitbuffer.COLOR_LIGHT_GRAY,
    ["Outer Rim Territories"] = Blitbuffer.COLOR_GRAY_D,
}
local REGION_ORDER = { "Deep Core", "Core Worlds", "Colonies", "Inner Rim",
    "Expansion Region", "Mid Rim", "Outer Rim Territories" }

local grid_data
local function loadGrid()
    if grid_data == nil then
        local dir = debug.getinfo(1, "S").source:match("^@(.*)/") or "."
        local ok, data = pcall(dofile, dir .. "/data/galaxy_grid.lua")
        if not ok then logger.warn("Wookieepedia: no galaxy grid data:", data) end
        grid_data = ok and data or false
    end
    return grid_data or nil
end

--- The canvas that paints the grid.
local GridCanvas = Widget:extend{
    width = nil,
    height = nil,
    grid = nil,      -- data/galaxy_grid.lua
    target = nil,    -- "L-9"
}

function GridCanvas:init()
    self.dimen = Geom:new{ w = self.width, h = self.height }
    self.label_face = Font:getFace("cfont", 12)
end

function GridCanvas:getSize()
    return self.dimen
end

function GridCanvas:paintTo(bb, x, y)
    self.dimen.x, self.dimen.y = x, y
    local grid = self.grid
    local ncols, nrows = #grid.cols, grid.rows_max - grid.rows_min + 1
    local margin = Screen:scaleBySize(22) -- room for the letters/numbers
    local cell = math.floor(math.min((self.width - margin) / ncols, (self.height - margin) / nrows))
    local ox = x + margin + math.floor((self.width - margin - cell * ncols) / 2)
    local oy = y + margin
    local target_col, target_row = (self.target or ""):match("^(%u)%-(%d+)$")
    target_row = tonumber(target_row)

    bb:paintRect(x, y, self.width, self.height, Blitbuffer.COLOR_WHITE)
    for ci, col in ipairs(grid.cols) do
        local cx = ox + (ci - 1) * cell
        local label = TextWidget:new{ text = col, face = self.label_face, bold = col == target_col }
        label:paintTo(bb, cx + math.floor((cell - label:getSize().w) / 2), y)
        label:free()
        for row = grid.rows_min, grid.rows_max do
            local cy = oy + (row - grid.rows_min) * cell
            local region = grid.cells[col .. "-" .. row]
            local shade = region and REGION_SHADES[region] or Blitbuffer.COLOR_WHITE
            if col == target_col and row == target_row then
                shade = Blitbuffer.COLOR_BLACK
            end
            bb:paintRect(cx, cy, cell, cell, shade)
            bb:paintBorder(cx, cy, cell + 1, cell + 1, 1, Blitbuffer.COLOR_GRAY_9)
        end
    end
    for row = grid.rows_min, grid.rows_max do
        local label = TextWidget:new{ text = tostring(row), face = self.label_face, bold = row == target_row }
        local cy = oy + (row - grid.rows_min) * cell
        label:paintTo(bb, ox - label:getSize().w - Screen:scaleBySize(4),
            cy + math.floor((cell - label:getSize().h) / 2))
        label:free()
    end
    -- A thick frame around the target so it stands out even on poor screens.
    if target_col and target_row then
        for ci, col in ipairs(grid.cols) do
            if col == target_col then
                local pad = Screen:scaleBySize(3)
                bb:paintBorder(ox + (ci - 1) * cell - pad, oy + (target_row - grid.rows_min) * cell - pad,
                    cell + 2 * pad + 1, cell + 2 * pad + 1, Screen:scaleBySize(2), Blitbuffer.COLOR_BLACK)
            end
        end
    end
end

local WookMap = InputContainer:extend{
    title = nil,
    location = nil,
}

function WookMap:init()
    local grid = loadGrid()
    local width, height = Screen:getWidth(), Screen:getHeight()
    self.dimen = Geom:new{ x = 0, y = 0, w = width, h = height }
    if Device:hasKeys() then
        self.key_events = { Close = { { Device.input.group.Back } } }
    end
    if Device:isTouchDevice() then
        self.ges_events = { Tap = { GestureRange:new{ ges = "tap", range = self.dimen } } }
    end

    local title_bar = TitleBar:new{
        width = width,
        fullscreen = true,
        title = self.title,
        subtitle = T(_("Grid square %1"), self.location.grid),
        with_bottom_line = true,
        close_callback = function() self:onClose() end,
        show_parent = self,
    }
    local legend_parts = {}
    for _, region in ipairs(REGION_ORDER) do
        if grid and grid.region_used[region] then table.insert(legend_parts, region) end
    end
    local legend = TextBoxWidget:new{
        text = T(_("Darker squares are closer to the galactic core: %1. Black: %2. White: no known planets. "
            .. "Shading follows the regions of planets Wookieepedia lists in each square."),
            table.concat(legend_parts, " → "), self.title),
        face = Font:getFace("x_smallinfofont"),
        width = width - 2 * Screen:scaleBySize(10),
    }
    local canvas_height = height - title_bar:getSize().h - legend:getSize().h - Screen:scaleBySize(20)
    local body
    if grid then
        body = GridCanvas:new{ width = width, height = canvas_height, grid = grid, target = self.location.grid }
    else
        body = TextBoxWidget:new{ text = _("Galaxy map data is missing."),
            face = Font:getFace("infofont"), width = width }
    end
    self[1] = FrameContainer:new{
        width = width,
        height = height,
        background = Blitbuffer.COLOR_WHITE,
        bordersize = 0,
        padding = 0,
        VerticalGroup:new{
            title_bar,
            body,
            FrameContainer:new{ bordersize = 0, padding = Screen:scaleBySize(10), legend },
        },
    }
end

function WookMap:onTap()
    return self:onClose()
end

function WookMap:onClose()
    UIManager:close(self)
    return true
end

function WookMap:onCloseWidget()
    UIManager:setDirty(nil, "flashui")
end

function WookMap:onShow()
    UIManager:setDirty(self, "flashui")
end

function WookMap:show(title, location)
    UIManager:show(WookMap:new{ title = title, location = location })
end

return WookMap
