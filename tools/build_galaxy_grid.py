#!/usr/bin/env python3
"""Turn data/planets.json (from tools/build_planet_grid.py) into
data/galaxy_grid.lua, the small table the map widget draws.

Each grid square gets the main region most of its listed planets belong to.
Empty squares surrounded mostly by one region take that region (one smoothing
pass), so the rings read as shapes rather than scattered dots."""
import collections, json, pathlib

DATA = pathlib.Path(__file__).resolve().parent.parent / "data"
MAIN = {  # Wookieepedia spelling -> map region (the concentric rings)
    "Deep Core": "Deep Core", "Core Worlds": "Core Worlds", "Colonies": "Colonies",
    "Inner Rim": "Inner Rim", "Inner Rim Territories": "Inner Rim",
    "Expansion Region": "Expansion Region",
    "Mid Rim": "Mid Rim", "Mid Rim Territories": "Mid Rim",
    "Outer Rim": "Outer Rim Territories", "Outer Rim Territories": "Outer Rim Territories",
}

planets = json.loads((DATA / "planets.json").read_text())
cols = [chr(c) for c in range(ord(min(p["col"] for p in planets)), ord(max(p["col"] for p in planets)) + 1)]
rmin, rmax = min(p["row"] for p in planets), max(p["row"] for p in planets)

votes = collections.defaultdict(collections.Counter)
counts = collections.Counter()
for p in planets:
    key = f'{p["col"]}-{p["row"]}'
    counts[key] += 1
    for r in p["region"]:
        if r in MAIN:
            votes[key][MAIN[r]] += 1
            break
cells = {k: v.most_common(1)[0][0] for k, v in votes.items()}

filled = dict(cells)
for ci, c in enumerate(cols):
    for r in range(rmin, rmax + 1):
        key = f"{c}-{r}"
        if key in cells:
            continue
        around = collections.Counter(
            cells[f"{cols[cj]}-{rr}"]
            for cj in range(max(0, ci - 1), min(len(cols), ci + 2))
            for rr in range(r - 1, r + 2)
            if f"{cols[cj]}-{rr}" in cells)
        if around and around.most_common(1)[0][1] >= 3:
            filled[key] = around.most_common(1)[0][0]

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["-- Generated by tools/build_galaxy_grid.py from Wookieepedia planet infoboxes. Do not edit.",
       "return {",
       "    cols = { " + ", ".join(lua_str(c) for c in cols) + " },",
       f"    rows_min = {rmin},", f"    rows_max = {rmax},",
       "    region_used = { " + ", ".join(f"[{lua_str(r)}] = true" for r in sorted(set(filled.values()))) + " },",
       "    cells = {"]
out += [f"        [{lua_str(k)}] = {lua_str(v)}," for k, v in sorted(filled.items())]
out += ["    },", "    planet_counts = {"]
out += [f"        [{lua_str(k)}] = {v}," for k, v in sorted(counts.items())]
out += ["    },", "}", ""]
(DATA / "galaxy_grid.lua").write_text("\n".join(out))
print(f"{len(cols)} cols {cols[0]}-{cols[-1]}, rows {rmin}-{rmax}, {len(cells)} squares with data, {len(filled)} after smoothing")
# ASCII preview
sym = {"Deep Core": "@", "Core Worlds": "#", "Colonies": "%", "Inner Rim": "+", "Expansion Region": "=", "Mid Rim": "-", "Outer Rim Territories": "."}
print("   " + "".join(cols))
for r in range(rmin, rmax + 1):
    print(f"{r:2} " + "".join(sym.get(filled.get(f"{c}-{r}"), " ") for c in cols))
